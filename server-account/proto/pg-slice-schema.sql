-- Study prototype: the tables and triggers the converted slice touches, ported by hand from
-- server-account/migrations/0001_schema.sql to Postgres. players keeps only the columns the slice needs.

CREATE TABLE players (
  id         TEXT PRIMARY KEY,
  guest_name TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  last_seen  BIGINT NOT NULL
);

CREATE TABLE marks (
  account TEXT PRIMARY KEY,
  balance BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0 AND balance <= 10000000),
  FOREIGN KEY (account) REFERENCES players(id) ON DELETE CASCADE
);

CREATE TABLE guild_marks (
  guild_id TEXT PRIMARY KEY,
  balance  BIGINT NOT NULL DEFAULT 0 CHECK (balance >= 0 AND balance <= 10000000)
);

-- SQLite's INTEGER PRIMARY KEY is its rowid alias: an identity column here.
CREATE TABLE marks_ledger (
  seq      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  src_kind TEXT NOT NULL CHECK (src_kind IN ('mint', 'account', 'guild', 'escrow')),
  src_id   TEXT,
  dst_kind TEXT NOT NULL CHECK (dst_kind IN ('burn', 'account', 'guild', 'escrow')),
  dst_id   TEXT,
  kind     TEXT NOT NULL,
  amount   BIGINT NOT NULL CHECK (amount > 0),
  day      INTEGER NOT NULL,
  at       BIGINT NOT NULL,
  actor    TEXT NOT NULL,
  who      TEXT,
  rid      TEXT NOT NULL,
  UNIQUE (actor, rid)
);
CREATE INDEX idx_marks_day ON marks_ledger (day);
CREATE INDEX idx_marks_dst ON marks_ledger (dst_id, kind, day);
CREATE INDEX idx_marks_ledger_escrow ON marks_ledger (dst_kind, src_kind, amount) WHERE dst_kind = 'escrow' OR src_kind = 'escrow';
CREATE INDEX idx_marks_src ON marks_ledger (src_id, kind, day);

-- SQLite's four AFTER INSERT ... WHEN triggers become one plpgsql function: each WHEN is an IF.
CREATE FUNCTION marks_line_pays() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.src_kind = 'account' THEN
    UPDATE marks SET balance = balance - NEW.amount WHERE account = NEW.src_id;
  ELSIF NEW.src_kind = 'guild' THEN
    UPDATE guild_marks SET balance = balance - NEW.amount WHERE guild_id = NEW.src_id;
  END IF;
  IF NEW.dst_kind = 'account' THEN
    INSERT INTO marks (account, balance) VALUES (NEW.dst_id, NEW.amount)
      ON CONFLICT (account) DO UPDATE SET balance = marks.balance + excluded.balance;
  ELSIF NEW.dst_kind = 'guild' THEN
    INSERT INTO guild_marks (guild_id, balance) VALUES (NEW.dst_id, NEW.amount)
      ON CONFLICT (guild_id) DO UPDATE SET balance = guild_marks.balance + excluded.balance;
  END IF;
  RETURN NULL;
END;
$$;
CREATE TRIGGER marks_line_pays AFTER INSERT ON marks_ledger FOR EACH ROW EXECUTE FUNCTION marks_line_pays();

CREATE TABLE broker_sales (
  account  TEXT NOT NULL,
  rid      TEXT NOT NULL,
  kind     TEXT NOT NULL,
  item     TEXT,
  at       BIGINT NOT NULL,
  settled  INTEGER NOT NULL DEFAULT 0,
  asked_by TEXT,
  PRIMARY KEY (account, rid),
  FOREIGN KEY (account) REFERENCES players(id) ON DELETE CASCADE
);

CREATE TABLE market_orders (
  id         TEXT PRIMARY KEY,
  poster     TEXT NOT NULL,
  char_id    TEXT NOT NULL,
  region     INTEGER NOT NULL CHECK (region >= 0 AND region <= 70),
  material   TEXT NOT NULL,
  units      INTEGER NOT NULL CHECK (units >= 1 AND units <= 5000),
  left_units INTEGER NOT NULL CHECK (left_units >= 0),
  price      INTEGER NOT NULL CHECK (price >= 1 AND price <= 1000000),
  escrow     BIGINT NOT NULL CHECK (escrow >= 0),
  at         BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  state      TEXT NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'filled', 'cancelled', 'expired')),
  closed_at  BIGINT,
  returned   INTEGER NOT NULL DEFAULT 0 CHECK (returned IN (0, 1)),
  rid        TEXT NOT NULL,
  n          TEXT NOT NULL,
  UNIQUE (poster, rid),
  FOREIGN KEY (poster) REFERENCES players(id) ON DELETE CASCADE
);
CREATE INDEX idx_market_orders_closed ON market_orders (closed_at);
CREATE INDEX idx_market_orders_open ON market_orders (state, region, material, price);
