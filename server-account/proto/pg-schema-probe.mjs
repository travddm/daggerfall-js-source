// Study prototype: how much of server-account/migrations ports to Postgres by mechanical rewrite alone. Each statement
// is rewritten by the rules below and run on PGlite; tables are retried in passes, because SQLite accepts a foreign key
// to a table created later and Postgres does not. Prints counts by statement kind and the commonest refusals.
// Usage: node server-account/proto/pg-schema-probe.mjs
import { readFileSync, readdirSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const dir = new URL('../migrations/', import.meta.url);
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();

/** Splits a migration into statements; a trigger body's inner semicolons stay with it. */
function statementsOf(text) {
  const noComments = text.replace(/--[^\n]*/g, '');
  const out = [];
  let current = '';
  let inTrigger = false;
  for (const line of noComments.split('\n')) {
    current += `${line}\n`;
    if (/^\s*CREATE\s+TRIGGER/i.test(line)) inTrigger = true;
    const ends = inTrigger ? /^\s*END\s*;\s*$/i.test(line) : /;\s*$/.test(line);
    if (ends) {
      if (current.trim()) out.push(current.trim());
      current = '';
      inTrigger = false;
    }
  }
  return out;
}

const rules = [
  [/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'],
  [/(\w+\s+)INTEGER PRIMARY KEY\b/gi, '$1BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'],
  [/\bINTEGER\b/gi, 'BIGINT'],
  [/\bREAL\b/gi, 'DOUBLE PRECISION'],
  [/\bBLOB\b/gi, 'BYTEA'],
  [/CAST\(strftime\('%s', 'now'\) AS INTEGER\)|CAST\(strftime\('%s', 'now'\) AS BIGINT\)/gi, 'CAST(EXTRACT(EPOCH FROM now()) AS BIGINT)'],
  [/\bINSERT OR IGNORE INTO\b/gi, 'INSERT INTO'],
];
const kindOf = (s) => (s.match(/^\s*(CREATE\s+(?:UNIQUE\s+)?(?:TABLE|INDEX|TRIGGER|VIEW)|ALTER TABLE|DROP\s+\w+|INSERT|UPDATE|DELETE|PRAGMA)/i)?.[1] ?? 'other').toUpperCase().replace(/\s+/g, ' ');

const pglite = new PGlite();
const tally = {};
const refusals = {};
let pending = [];
for (const f of files) for (const s of statementsOf(readFileSync(new URL(f, dir), 'utf8'))) pending.push({ f, s });

for (let pass = 0; pass < 6 && pending.length; pass++) {
  const next = [];
  for (const item of pending) {
    const kind = kindOf(item.s);
    tally[kind] ??= { ok: 0, refused: 0 };
    if (kind === 'CREATE TRIGGER' || kind === 'PRAGMA') {
      if (pass === 0) tally[kind].refused++;
      if (pass === 0) refusals[`${kind}: needs a plpgsql function (by hand)`] = (refusals[`${kind}: needs a plpgsql function (by hand)`] ?? 0) + 1;
      continue;
    }
    let sqlText = item.s;
    for (const [from, to] of rules) sqlText = sqlText.replace(from, to);
    try {
      await pglite.exec(sqlText);
      tally[kind].ok++;
    } catch (e) {
      const message = String(e.message).replace(/"[^"]*"/g, '"x"').slice(0, 90);
      if (/does not exist/.test(message) && pass < 5) next.push(item);
      else {
        tally[kind].refused++;
        refusals[`${kind}: ${message}`] = (refusals[`${kind}: ${message}`] ?? 0) + 1;
      }
    }
  }
  pending = next;
}

for (const [kind, n] of Object.entries(tally)) console.log(`${kind}: ${n.ok} ported, ${n.refused} refused`);
console.log('Commonest refusals:');
for (const [why, n] of Object.entries(refusals).sort((a, b) => b[1] - a[1]).slice(0, 12)) console.log(`  ${n} x ${why}`);
await pglite.close();
