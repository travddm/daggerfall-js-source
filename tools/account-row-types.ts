#!/usr/bin/env node
// Writes server-account/src/database-types.ts, the row shapes Kysely types the account service's queries with, from
// the SQLite schema that the migrations build. The schema is the source of truth: a column added by a migration reaches
// the types by running this tool, and test/tooling/account-row-types.test.ts fails while the file is stale.
//
//   node tools/account-row-types.ts           # write the file
//   node tools/account-row-types.ts --check   # exit 1 when the file differs from what the migrations give

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { fileURLToPath } from 'node:url';

export const MIGRATIONS_DIR = fileURLToPath(new URL('../server-account/migrations/', import.meta.url));
export const ROW_TYPES_PATH = fileURLToPath(new URL('../server-account/src/database-types.ts', import.meta.url));

/** One column as `PRAGMA table_xinfo` reports it. */
interface ColumnInfo {
  name: string;
  type: string;
  notnull: number;
  dflt_value: string | null;
  pk: number;
  hidden: number;
}

/** One table as `PRAGMA table_list` reports it (`wr` is 1 for a WITHOUT ROWID table). */
interface TableInfo {
  name: string;
  type: string;
  wr: number;
}

/** A database with every migration applied, in file-name order, as `wrangler d1 migrations apply` applies them. */
export function migratedDatabase(migrationsDir: string = MIGRATIONS_DIR): DatabaseSync {
  const db = new DatabaseSync(':memory:');
  const files = readdirSync(migrationsDir)
    .filter((file) => file.endsWith('.sql'))
    .sort();
  for (const file of files) db.exec(readFileSync(`${migrationsDir}/${file}`, 'utf8'));
  return db;
}

/** The TypeScript type of a value SQLite stores under a declared column type, by SQLite's type-affinity rules. */
function valueTypeOf(declared: string): string {
  const type = declared.toUpperCase();
  if (type.includes('INT')) return 'number';
  if (type.includes('CHAR') || type.includes('CLOB') || type.includes('TEXT')) return 'string';
  if (type === '' || type.includes('BLOB')) return 'Uint8Array';
  return 'number';
}

/** `broker_sales` -> `BrokerSalesTable`. */
const interfaceNameOf = (table: string): string =>
  `${table
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')}Table`;

/** A property name as TypeScript and Prettier write it: bare when it is an identifier, quoted otherwise. */
const propertyNameOf = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`);

/** One column's property line. */
function columnLine(column: ColumnInfo, rowidAlias: boolean): string {
  let type = valueTypeOf(column.type);
  // SQLite enforces NOT NULL only where it is declared, and a key column outside a rowid alias may hold NULL.
  if (!column.notnull && !rowidAlias) type = `${type} | null`;
  // A column the database fills when an insert leaves it out: a default, or the rowid an INTEGER PRIMARY KEY names.
  if (column.dflt_value !== null || rowidAlias) type = `Generated<${type}>`;
  return `  ${propertyNameOf(column.name)}: ${type};`;
}

/** The source text of database-types.ts for the schema in `db`. */
export function rowTypesSource(db: DatabaseSync): string {
  const tables = (db.prepare('PRAGMA table_list').all() as unknown as TableInfo[])
    .filter((table) => table.type === 'table' && !table.name.startsWith('sqlite_'))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
  const blocks: string[] = [];
  for (const table of tables) {
    const columns = db.prepare(`PRAGMA table_xinfo("${table.name}")`).all() as unknown as ColumnInfo[];
    const keys = columns.filter((column) => column.pk > 0);
    const visible = columns.filter((column) => column.hidden === 0);
    const lines = visible.map((column) => {
      const rowidAlias = !table.wr && keys.length === 1 && column.pk > 0 && column.type.toUpperCase() === 'INTEGER';
      return columnLine(column, rowidAlias);
    });
    blocks.push(`export interface ${interfaceNameOf(table.name)} {\n${lines.join('\n')}\n}\n`);
  }
  const database = tables.map((table) => `  ${propertyNameOf(table.name)}: ${interfaceNameOf(table.name)};`);
  return [
    '// Generated by tools/account-row-types.ts from the SQLite schema that server-account/migrations builds. Do not edit',
    '// it by hand: run `node tools/account-row-types.ts` after a migration. test/tooling/account-row-types.test.ts fails',
    '// while it is stale.',
    '',
    "import type { Generated } from 'kysely';",
    '',
    ...blocks,
    `export interface Database {\n${database.join('\n')}\n}\n`,
  ].join('\n');
}

function main(): void {
  const source = rowTypesSource(migratedDatabase());
  if (process.argv.includes('--check')) {
    if (readFileSync(ROW_TYPES_PATH, 'utf8') !== source) {
      console.error('server-account/src/database-types.ts is stale: run node tools/account-row-types.ts');
      process.exit(1);
    }
    return;
  }
  writeFileSync(ROW_TYPES_PATH, source);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
